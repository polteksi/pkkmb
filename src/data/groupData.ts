export const ALL_STUDENTS: StudentMember[] = GROUPS_DATA.flatMap((group) => group.members);

export const getGenderLabel = (gender: StudentMember['gender']): string => {
  if (gender === 'L') return 'Laki-laki';
  if (gender === 'P') return 'Perempuan';
  return 'Belum diisi';
};

const normalizeSearchText = (value: string): string =>
  value
    .toLocaleLowerCase('id-ID')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

export const matchesStudentSearch = (student: StudentMember, query: string): boolean => {
  const normalizedQuery = normalizeSearchText(query);
  if (!normalizedQuery) return true;

  const searchableText = normalizeSearchText([
    student.name,
    student.major,
    student.groupName,
    student.groupAlias,
    student.mentorName,
    getGenderLabel(student.gender),
  ].join(' '));

  return searchableText.includes(normalizedQuery);
};
